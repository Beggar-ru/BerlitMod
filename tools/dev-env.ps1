# Shell setup for this checkout. Two ways to use it:
#
#   1) Run a task directly:
#        .\tools\dev-env.ps1 build
#        .\tools\dev-env.ps1 runClient
#        .\tools\dev-env.ps1 preview check
#
#   2) Load it into the session (note the leading dot and space):
#        . .\tools\dev-env.ps1
#        gw build
#        pv check
#
# It points JAVA_HOME at the workspace-local JDK 25, GRADLE_USER_HOME at
# .gradle-home and TMP/TEMP at .gradle-home\tmp, since neither %USERPROFILE%\.gradle
# nor the system %TEMP% is usable for this checkout. It also generates
# .gradle-home\gradle.properties and installs tools\env\local-mirror.gradle into
# .gradle-home\init.d, so the build finds the JDK toolchains and the local jar
# mirror without any manual setup.

param(
    [Parameter(ValueFromRemainingArguments = $true)]
    [string[]] $Task
)

$root = Split-Path -Parent $PSScriptRoot

# --- JDKs ------------------------------------------------------------------
$jdk = Join-Path $root '.tools\jdk-25'
if (Test-Path (Join-Path $jdk 'bin\java.exe')) {
    $env:JAVA_HOME = $jdk
    $env:PATH = "$jdk\bin;$env:PATH"
} else {
    Write-Warning "JDK 25 not found in .tools\jdk-25 - run: python tools\env\fetch_jdks.py"
}

# --- Gradle home -----------------------------------------------------------
$gradleHome = Join-Path $root '.gradle-home'
foreach ($sub in @('', 'tmp', 'init.d')) {
    $dir = if ($sub) { Join-Path $gradleHome $sub } else { $gradleHome }
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
}
$env:GRADLE_USER_HOME = $gradleHome

# Spotless/blowdryer cannot write its cache into the system %TEMP% here, so both
# the shell and the Gradle JVM use a workspace temp directory.
$temp = Join-Path $gradleHome 'tmp'
$env:TMP = $temp
$env:TEMP = $temp

# Machine settings that cannot live in the repository: absolute toolchain paths
# and the sandbox workarounds. Written once, then left alone so local edits stick.
$envProps = Join-Path $gradleHome 'gradle.properties'
if (-not (Test-Path $envProps)) {
    $toolchains = @('jdk-25', 'jdk-21', 'jdk-17', 'jdk-8') |
        ForEach-Object { Join-Path $root ".tools\$_" } |
        Where-Object { Test-Path (Join-Path $_ 'bin\java.exe') } |
        ForEach-Object { $_ -replace '\\', '/' }
    $tmpDir = $temp -replace '\\', '/'

    $lines = @(
        '# Generated by tools\dev-env.ps1 - machine-specific Gradle settings.'
        '# Delete this file to regenerate it; paths below are absolute.'
        ''
        '# --- Sandbox ---------------------------------------------------------------'
        '# Under the DSH file sandbox Gradle cannot open native threads for file watching'
        '# and fails with "Couldn''t open current thread, error = 5". Both features go off.'
        'org.gradle.vfs.watch=false'
        'org.gradle.native=false'
        ''
        '# Spotless/blowdryer cannot create its cache in the system %TEMP% here.'
        "org.gradle.jvmargs=-Xmx4G -Dfile.encoding=UTF-8 -Djava.io.tmpdir=$tmpDir"
        ''
        '# --- Toolchains ------------------------------------------------------------'
        '# Installed into .tools by tools\env\fetch_jdks.py, not into Program Files.'
        "org.gradle.java.installations.paths=$($toolchains -join ',')"
        'org.gradle.java.installations.auto-download=false'
        'org.gradle.java.installations.auto-detect=true'
        ''
        '# --- Network ---------------------------------------------------------------'
        '# nexus.gtnewhorizons.com never delivers jar bodies on this network (see'
        '# tools\env\mirror.py); fail fast instead of hanging a minute per artifact.'
        'systemProp.org.gradle.internal.http.connectionTimeout=15000'
        'systemProp.org.gradle.internal.http.socketTimeout=20000'
        ''
        '# --- Misc ------------------------------------------------------------------'
        'org.gradle.parallel=true'
        'org.gradle.caching=true'
        '# RFG''s Download task cannot be serialized into the configuration cache.'
        'org.gradle.configuration-cache=false'
    )
    # Windows PowerShell 5.1 writes a BOM with -Encoding UTF8, which Gradle then
    # reads as part of the first key, so the file is written UTF-8 without BOM.
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($envProps, ($lines -join "`r`n") + "`r`n", $utf8NoBom)
}

# The jar mirror has to be in front of the GTNH Nexus before settings.gradle.kts
# is evaluated; init.d is where Gradle picks init scripts up from. It is copied on
# every run so the generated copy never goes stale against tools\env\local-mirror.gradle.
$initSrc = Join-Path $root 'tools\env\local-mirror.gradle'
$initDst = Join-Path $gradleHome 'init.d\local-mirror.gradle'
if (Test-Path $initSrc) {
    Copy-Item $initSrc $initDst -Force
}

if (-not (Test-Path (Join-Path $root '.tools\local-maven'))) {
    Write-Warning "Jar mirror not found - run: python tools\env\mirror.py"
}
if (-not (Test-Path (Join-Path $root '.tools\jdk-25'))) {
    Write-Warning "JDK toolchains missing - run: python tools\env\fetch_jdks.py"
}

# --- Helpers ---------------------------------------------------------------
# Python for the texture/GUI tools: recorded by the setup step, else PATH.
$pythonFile = Join-Path $root '.tools\python.txt'
$python = if (Test-Path $pythonFile) {
    ((Get-Content $pythonFile -Raw) -replace '^\uFEFF', '').Trim()
} else { 'python' }

$gwPath = Join-Path $root 'gradlew.bat'
$pvPath = Join-Path $root 'tools\preview.py'

# Native file watching and native integration fail under the sandbox with
# "Couldn't open current thread, error = 5". Both are switched off in
# .gradle-home/gradle.properties; --no-watch-fs is the belt-and-braces flag.
function Invoke-BerlitGradle {
    & $gwPath --no-watch-fs @args
}

function Invoke-BerlitPreview {
    & $python $pvPath @args
}

# Arguments were passed, so this file was run rather than dot-sourced: execute.
# The command output must go straight to the pipeline - wrapping it in exit (...)
# would capture and discard it - so exit with $LASTEXITCODE afterwards.
if ($Task.Count -gt 0) {
    if ($Task[0] -in @('preview', 'pv')) {
        & $python $pvPath @($Task | Select-Object -Skip 1)
    } else {
        & $gwPath --no-watch-fs @Task
    }
    exit $LASTEXITCODE
}

# Run with no arguments means the user expected something to happen; the helpers
# only survive dot-sourcing, so say that instead of silently defining and leaving.
if ($MyInvocation.InvocationName -ne '.') {
    Write-Host 'Usage:'
    Write-Host '  .\tools\dev-env.ps1 build            # run a Gradle task'
    Write-Host '  .\tools\dev-env.ps1 runClient'
    Write-Host '  .\tools\dev-env.ps1 preview check    # run a preview.py command'
    Write-Host ''
    Write-Host 'Or load the environment into this session (note the leading dot):'
    Write-Host '  . .\tools\dev-env.ps1'
    Write-Host '  gw build / gw runClient / pv check'
    exit 0
}

# Dot-sourced: publish the helpers into the caller's session. The paths are baked
# into the bodies so the functions keep working after this script has returned.
Set-Item -Path Function:global:gw -Value ([scriptblock]::Create("& '$gwPath' --no-watch-fs @args"))
Set-Item -Path Function:global:pv -Value ([scriptblock]::Create("& '$python' '$pvPath' @args"))

Write-Host "JAVA_HOME        = $env:JAVA_HOME"
Write-Host "GRADLE_USER_HOME = $env:GRADLE_USER_HOME"
Write-Host "TMP              = $env:TMP"
Write-Host "python           = $python"
Write-Host "Ready: 'gw build', 'gw runClient', 'pv check', 'pv sheet'."
